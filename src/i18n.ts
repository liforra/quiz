// Merges a question's translations[lang] over its base fields. Falls back to
// the original (untranslated) field whenever no translation was supplied —
// quiz authors are never required to translate everything.
export function resolveQuestionLang(question: any, lang: Lang): any {
  if (!question) return question;
  const translation = question.translations?.[lang];
  if (!translation) return question;
  return {
    ...question,
    question: translation.question ?? question.question,
    options: translation.options ?? question.options,
    answer: translation.answer ?? question.answer,
    explanation: translation.explanation ?? question.explanation,
    category: translation.category ?? question.category,
  };
}
